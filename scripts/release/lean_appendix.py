#!/usr/bin/env python3
"""Write a LaTeX appendix that prints complete Lean declarations, with default-branch and
commit-pinned links to each, from a JSON configuration.

  lean_appendix.py CONFIG.json

CONFIG keys: "repo" (https://github.com/OWNER/NAME), "lean_dir" (repository-relative
directory of the Lean files), "out" (output .tex, relative to CONFIG), "default_pin"
(commit), and "groups": a list of {"title", "file", "names", optional "pin"}.
Each declaration (with a doc comment directly above it) is taken from the working tree and
must be byte-identical, at the same line, at its pinned commit; otherwise the script fails,
so the default-branch and pinned links always show the same proof. Unicode is converted for
listings' escapeinside={(*@}{@*)}; an unmapped character is an error.
Part of the verified-release skill (.agents/skills/verified-release).
"""
import json, re, subprocess, sys
from pathlib import Path

START = re.compile(r'^\s*(?:private |protected )?(?:noncomputable )?(theorem|lemma|def|structure|inductive|abbrev) ([^\s:({\[]+)')
TOP = re.compile(r'^(?:\s?(?:private |protected )?(?:noncomputable )?(?:theorem|lemma|def|structure|inductive|abbrev|instance)\b|/-|#|@\[|end |section|namespace|open |variable|set_option)')

def extract(lines, name):
    for i, l in enumerate(lines):
        m = START.match(l)
        if m and m.group(2) == name:
            j = i + 1
            while j < len(lines) and not TOP.match(lines[j]):
                j += 1
            while lines[j - 1].strip() == '':
                j -= 1
            # include a doc comment directly above
            k = i
            if k > 0 and lines[k - 1].rstrip().endswith('-/'):
                while not lines[k - 1].lstrip().startswith('/-'):
                    k -= 1
                k -= 1
            return i + 1, '\n'.join(lines[k:j])
    raise SystemExit(f'declaration {name} not found')

SYM = {'→': r'\to', '↔': r'\leftrightarrow', '∀': r'\forall', '∃': r'\exists', '∈': r'\in',
       '∉': r'\notin', '≤': r'\le', '≥': r'\ge', '≠': r'\ne', '¬': r'\neg', '∧': r'\wedge',
       '∨': r'\vee', 'ℕ': r'\mathbb N', 'ℤ': r'\mathbb Z', '⟨': r'\langle', '⟩': r'\rangle',
       '·': r'\cdot', '∑': r'\sum', '⬝': r'\cdot', 'ᵥ': r'_v', '×': r'\times', '∘': r'\circ',
       'σ': r'\sigma', 'φ': r'\varphi', 'π': r'\pi', 'τ': r'\tau', 'α': r'\alpha', 'β': r'\beta',
       'γ': r'\gamma', 'ι': r'\iota', 'κ': r'\kappa', 'λ': r'\lambda', 'ω': r'\omega',
       '≃': r'\simeq', '⁻': r'^{-}', '¹': r'^{1}', '₀': r'_0', '₁': r'_1', '₂': r'_2', 'ᵀ': r'^{\mathsf T}',
       '⊆': r'\subseteq', '∩': r'\cap', '∪': r'\cup', '∅': r'\emptyset', '≫': r'\gg', '▸': r'\triangleright',
       '⦃': r'\{\!|', '⦄': r'|\!\}', '‖': r'\|', '⊥': r'\bot', '⊤': r'\top', '∣': r'\mid', '•': r'\bullet',
       '⁅': '[', '⁆': ']', '×ˢ': r'\times', 'ˢ': r'^s', '⊔': r'\sqcup', '⊓': r'\sqcap', 'Δ': r'\Delta', 'Σ': r'\Sigma'}

SYM.update({'ψ': r'\psi', '←': r'\leftarrow', '—': '--', '–': '-', 'ᵢ': r'_i', 'ⁿ': r'^n',
            '⁸': r'^8', '⊢': r'\vdash', '…': r'\ldots', 'δ': r'\delta', 'ₗ': r'_l', '↥': r'\uparrow',
            '≅': r'\cong', '₆': r'_6'})

def tex(code):
    out = []
    for ch in code:
        if ord(ch) < 128:
            out.append(ch)
        elif ch in SYM:
            out.append('(*@\\ensuremath{' + SYM[ch] + '}@*)')
        else:
            raise SystemExit(f'no LaTeX mapping for {ch!r} (U+{ord(ch):04X})')
    return ''.join(out)

def ttname(s):
    return s.replace('_', r'\_')



def build(config_path):
    cfg_path = Path(config_path).resolve()
    cfg = json.loads(cfg_path.read_text())
    root = Path(subprocess.run(['git', 'rev-parse', '--show-toplevel'], capture_output=True, text=True,
                               cwd=cfg_path.parent).stdout.strip())
    repo, ldir = cfg['repo'], cfg['lean_dir']
    def show(rev, f):
        r = subprocess.run(['git', 'show', f'{rev}:{ldir}/{f}'], capture_output=True, text=True, cwd=root)
        if r.returncode:
            raise SystemExit(f'cannot read {f} at {rev}')
        return r.stdout.split('\n')
    parts = ['% Generated by lean_appendix.py from ' + cfg_path.name + '. Do not edit.']
    count = 0
    for g in cfg['groups']:
        f, pin = g['file'], g.get('pin', cfg.get('default_pin'))
        cur = (root / ldir / f).read_text().split('\n')
        old = show(pin, f)
        parts.append(r'\subsection*{' + g['title'] + r' (\texttt{' + ttname(f) + '})}')
        for n in g['names']:
            line, body = extract(cur, n)
            if (line, body) != extract(old, n):
                raise SystemExit(f'{f}:{n} differs between the working tree and pinned {pin[:8]}')
            parts.append(r'\noindent\href{' + f'{repo}/blob/master/{ldir}/{f}\\#L{line}' + r'}{\texttt{'
                         + ttname(n) + r'}}~(\href{' + f'{repo}/blob/{pin}/{ldir}/{f}\\#L{line}'
                         + r'}{pinned}), line ' + str(line) + '.')
            parts.append(r'\begin{lstlisting}' + '\n' + tex(body) + '\n' + r'\end{lstlisting}')
            count += 1
    out = cfg_path.parent / cfg['out']
    out.write_text('\n'.join(parts) + '\n')
    print(f'wrote {out.name}: {count} declarations')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    build(sys.argv[1])
