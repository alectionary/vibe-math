"""Exhaustive, symmetry-reduced 3x3 search at a fixed lift size.

Objective: simple eight-cycles = four-variable absorbing sets when every
variable has degree three and girth is eight. Python evidence, not Lean.
"""
from collections import Counter
from itertools import permutations, product
from math import gcd
from pathlib import Path
import argparse
import hashlib
import json
from decoding import exclusions, components, cycles8_projection, cycles8_dfs
from scan import voltage_graph, matrix_graph, girth


def matrix(t):
    a, b, c, d = t
    return [[0, 0, 0], [0, a, b], [0, c, d]]


def orbit(t, r):
    """Graph isomorphisms: row/column relabeling, gauge, unit, transpose.

    B'ij = Bij+ui+vj is realized by fiber shifts
    C(i,j):ui-vj, L(k,j):-vk-vj, R(i,l):ui+ul.
    Transposing B exchanges L/R, swaps check indices, negates fibers.
    Multiplication by a unit rescales every fiber. Thus all preserve cycles.
    """
    B = matrix(t)
    out = set()
    units = [u for u in range(r) if gcd(u, r) == 1]
    for rows in permutations(range(3)):
        for cols in permutations(range(3)):
            q = tuple((B[rows[i]][cols[j]]-B[rows[i]][cols[0]]-
                       B[rows[0]][cols[j]]+B[rows[0]][cols[0]]) % r
                      for i, j in [(1, 1), (1, 2), (2, 1), (2, 2)])
            for u in units:
                a, b, c, d = (u*x % r for x in q)
                out.add((a, b, c, d))
                out.add((a, c, b, d))
    return out


def run(r):
    # A normalized connected lift has cycle-voltage subgroup generated by
    # its four interior entries: connected iff gcd(r,a,b,c,d)=1.
    valid = {t for t in product(range(1, r), repeat=4)
             if gcd(r, *t) == 1 and exclusions(matrix(t), r)}
    unseen = set(valid)
    classes = []
    while unseen:
        t = min(unseen)
        orb = orbit(t, r)
        assert orb <= valid
        assert orb <= unseen, 'orbits must partition the valid set'
        unseen.difference_update(orb)
        B = matrix(t)
        adj = voltage_graph(B, r)
        assert components(adj) == [27*r]
        counts = cycles8_projection(adj)
        classes.append({'interior': t, 'orbit_size': len(orb),
                        'eight_cycles': sum(counts.values()),
                        'eight_cycles_by_left_variable_count': counts})
    classes.sort(key=lambda x: (x['eight_cycles'], x['interior']))
    assert sum(x['orbit_size'] for x in classes) == len(valid)
    best = classes[0]['eight_cycles']
    winners = [x for x in classes if x['eight_cycles'] == best]
    for x in winners:
        B = matrix(x['interior'])
        adj = voltage_graph(B, r)
        assert adj == matrix_graph(B, r) and girth(adj) == 8
        assert cycles8_dfs(adj) == x['eight_cycles_by_left_variable_count']
    histogram = Counter()
    for x in classes:
        histogram[x['eight_cycles']] += x['orbit_size']
    return {'scope': 'All normalized fully populated 3x3 bases at the stated lift size; exact Python enumeration, not a Lean optimality proof.',
            'r': r, 'normalized_search_space': (r-1)**4,
            'connected_girth_eight_bases': len(valid),
            'isomorphism_orbits': len(classes), 'minimum_eight_cycles': best,
            'minimizer_count': sum(x['orbit_size'] for x in winners),
            'minimizing_orbits': winners,
            'cycle_histogram_weighted_by_bases': dict(sorted(histogram.items())),
            'orbits': classes,
            'source_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--r', type=int, default=14)
    args = parser.parse_args()
    result = run(args.r)
    Path(__file__).with_name(f'optimization-r{args.r}.json').write_text(json.dumps(result, indent=2)+'\n')
    print(json.dumps({k: v for k, v in result.items() if k != 'orbits'}, indent=2))
