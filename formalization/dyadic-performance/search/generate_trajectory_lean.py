"""Generate explicit frozen-graph data; the proof body is maintained separately."""
from pathlib import Path
import json
import trajectory as tr
HERE=Path(__file__).resolve().parent

def literal(value):
    if isinstance(value,list):return '['+', '.join(map(literal,value))+']'
    if isinstance(value,bool):return str(value).lower()
    return str(value)


def data_source():
    data=json.loads((HERE/'trajectory-results.json').read_text())
    record=next(r for r in data['records'] if (r['profile'],r['representative'],r['sector'])==(2,0,'x'))
    witness=next(p for p in record['pairs'] if p['error_hex']=='0x20001')
    h=record['check_rows'];edges,ce,ve=tr.edge_data(h,32);part=witness['partition']
    defs=[('labelRows','List (List Nat)',record['bz']),
          ('edgeVariableData','List Nat',[v for c,v in edges]),
          ('checkInputsData','List (List (Fin 128))',[[k for k in ce[c] if k!=j] for j,(c,v) in enumerate(edges)]),
          ('postInputsData','List (List (Fin 128))',ve),
          ('qClassData','List (Fin 7)',part['q_classes']),
          ('rClassData','List (Fin 7)',part['r_classes']),
          ('pClassData','List (Fin 3)',part['posterior_classes']),
          ('targetData','List Bool',[bool(int(witness['target_syndrome_hex'],16)>>c&1) for c in range(16)])]
    rc=part['r_classes'];qc=part['q_classes'];pc=part['posterior_classes']
    rs=[];rt=[];qs=[];ps=[]
    for col in range(7):
        j=rc.index(col);c,v=edges[j];rs.append([qc[k] for k in ce[c] if k!=j]);rt.append(bool(int(witness['target_syndrome_hex'],16)>>c&1))
        j=qc.index(col);c,v=edges[j];qs.append([rc[k] for k in ve[v] if k!=j])
    for col in range(3):
        v=pc.index(col);ps.append([rc[j] for j in ve[v]])
    defs += [('rowClassesData','List (List (Fin 3))',[[pc[v] for v in row] for row in h]),('rInputClasses','List (List (Fin 7))',rs),('rTarget','List Bool',rt),
             ('qInputClasses','List (List (Fin 7))',qs),('pInputClasses','List (List (Fin 7))',ps)]
    head='''import Mathlib.Algebra.Order.BigOperators.Group.Finset
import Mathlib.Tactic.FinCases
import Mathlib.Tactic.Abel

/-! Frozen Construction 3.10 profile 2, representative 0, X sector, error {0,17}.
All-iterations min-sum obstruction, including the concrete graph/update bridge.
Data generated by search/generate_trajectory_lean.py; proof body maintained in
search/trajectory-proof-body.txt. No claim of a new general symmetry principle. -/
set_option maxRecDepth 20000
set_option maxHeartbeats 8000000
set_option linter.unusedSimpArgs false

namespace DyadicMinSumTrajectory

'''
    return head+'\n'.join('def '+name+' : '+ty+' := '+literal(value)+'\n' for name,ty,value in defs)


if __name__=='__main__':
    body=(HERE/'trajectory-proof-body.txt').read_text()
    (HERE.parents[1]/'dyadic-rank/DyadicMinSumTrajectory.lean').write_text(data_source()+body)
