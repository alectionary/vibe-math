def controls():
 counts=Counter();covers=0
 for mask in range(128):
  E=[i+1 for i in range(7) if mask>>i&1];tri=[t for t in combinations(E,3) if t[0]^t[1]^t[2]==0];four=[t for t in combinations(E,4) if t[0]^t[1]^t[2]^t[3]==0];rank=len(basis(E));family=[(1<<(v-1),1) for v in E]+[(sum(1<<(v-1) for v in t),2) for t in tri]
  if four:family.append((mask,3));counts['contains_four_circuit']+=1
  elif rank==3:
   assert len(E)<=4
   if len(E)==4:assert len(tri)==1;counts['triangle_plus_coloop']+=1
   else:assert len(E)==3;counts['independent_rank3']+=1
  else:counts['rank_below3']+=1
  cost={0:0}
  for S,r in family:
   for T,c in list(cost.items()):cost[T|S]=min(cost.get(T|S,100),c+r)
  S=mask
  while True:
   expected=len(basis(v for v in E if S>>(v-1)&1));cover=min(c for T,c in cost.items() if T&S==S);assert cover==expected;covers+=1
