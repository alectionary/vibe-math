#!/usr/bin/env python3
"""Authenticated, balanced Nat-chunk prototype; no string-to-Nat proof bridge.
This prototype is not imported by the C16 library and does not prove acceptance.
"""
import argparse,gzip,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
p=argparse.ArgumentParser();p.add_argument('--output',type=Path,default=Path(__file__).with_name('PackedData.lean'));a=p.parse_args()
manifest=ROOT/'restricted-frames-20261031/certificates/MANIFEST.json'
m=json.loads(manifest.read_text())
inst=ROOT/'restricted-frames-20261031/certificates/swap.inst'
cert=ROOT/'restricted-frames-20261031/certificates/swap.cert.gz'
def verified(path):
 b=path.read_bytes();assert hashlib.sha256(b).hexdigest()==m[str(path.relative_to(ROOT))]['sha256'];return b
lines=verified(inst).decode().splitlines();nx,nz,ni,dim=map(int,lines[0].split());assert (nx,nz,dim)==(720,720,128)
def vec(s):
 lo,hi=s.split();return int(lo,16)+(int(hi,16)<<64)
assert vec(lines[1])==2**128-1
x=list(map(vec,lines[2:2+nx]));z=list(map(vec,lines[2+nx:2+nx+nz]))
poolfiles=[ROOT/'pools/xcoords.txt',ROOT/'pools/zcoords.txt']
for vals,path in zip([x,z],poolfiles):assert vals==[int(v,16) for v in path.read_text().split()]
assert len(lines)==2+nx+nz+ni
keys=[]
for line in lines[2+nx+nz:]:
 r=list(map(int,line.split()));n=r[0];pairs=list(zip(r[1::2],r[2::2]));assert len(r)==1+2*n and n in (1,2)
 i,j=pairs[0];assert 0<=i<nx and 0<=j<nz
 assert pairs==([(i,j)] if i==j else [(i,j),(j,i)])
 keys.append(i+(j<<10))
records=gzip.decompress(verified(cert)).decode().splitlines();h=records[0].split()
assert h[:2]==['C16CERT','1'] and len(h)==14
assert dict(zip(h[2::2],map(int,h[3::2])))==dict(need=128,items=ni,live_sides=1,shard=0,nshard=1,shard_depth=0)
assert records[-1]=='END COMPLETE'
op={'R':(0,0),'E':(1,2),'B':(2,3),'C':(3,1),'K':(4,1),'S':(5,1),'F':(6,0)}
tokens=[]
for line in records[1:-1]:
 r=line.split();code,n=op[r[0]];assert len(r)==n+1
 args=list(map(int,r[1:]));assert all(v>=0 for v in args);tokens.extend([code,*args])
def tree(vals,width,chunk=256):
 assert vals and all(0<=v<2**width for v in vals)
 if len(vals)<=chunk:
  bits=sum(v<<(width*i) for i,v in enumerate(vals));return f'(.leaf {len(vals)} 0x{bits:x})'
 mid=(len(vals)//2//chunk)*chunk
 if not mid:mid=len(vals)//2
 return f'(.node {mid} {len(vals)}\n {tree(vals[:mid],width,chunk)}\n {tree(vals[mid:],width,chunk)})'
inputs=[manifest,inst,cert,*poolfiles,ROOT/'lean/PoolData.lean']
header='/- Generated by kernel-only/packed/generate.py. Prototype only.\n'+''.join('   '+str(f.relative_to(ROOT))+' sha256 '+hashlib.sha256(f.read_bytes()).hexdigest()+'\n' for f in inputs)+'-/\n'
s=header+'import PackedCore\nimport PoolData\nimport CertGPTCheck\nnamespace C16Frames.PackedPrototype\n'
for name,vals,width,ch in [('xChunks',x,128,16),('zChunks',z,128,16),('itemChunks',keys,20,256),('tokenChunks',tokens,14,256)]:
 s+=f'def {name} : Chunks :=\n{tree(vals,width,ch)}\n\n'
s+=f'''def xVectors : Array Nat := (read 128 xChunks {nx} 0).toArray
def zVectors : Array Nat := (read 128 zChunks {nz} 0).toArray
def itemCount : Nat := {ni}
def tokenCount : Nat := {len(tokens)}
def instanceData : C16Frames.CertGPT.Instance := {{
  x := xVectors, z := zVectors,
  items := ((read 20 itemChunks itemCount 0).map fun k =>
    C16Frames.CertGPT.orbit "swap" (k % 1024) (k / 1024)).toArray }}
def tokenArray : Array Nat := (read 14 tokenChunks tokenCount 0).toArray
set_option maxRecDepth 100000
set_option maxHeartbeats 0
theorem x_eq_pool : xVectors = C16Frames.Pools.xArr := by
  apply Array.toList_inj.mp
  rfl
theorem z_eq_pool : zVectors = C16Frames.Pools.zArr := by
  apply Array.toList_inj.mp
  rfl
#print axioms x_eq_pool
#print axioms z_eq_pool
end C16Frames.PackedPrototype
'''
a.output.write_text(s)
# Extract exactly the real root's child list, skipping complete subtrees.
body=records[1:-1]
def skip_node(pos):
 r=body[pos].split();pos+=1
 if r[0] in ('R','E'):return pos
 assert r[0]=='B'
 for _ in range(int(r[3])):
  child=body[pos].split();pos+=1;assert child[0] in ('C','K')
  if child[0]=='C':pos=skip_node(pos)
 return pos
r=body[0].split();assert r[0]=='B';pos=1;children=[]
for _ in range(int(r[3])):
 child=body[pos].split();pos+=1;children.append(int(child[1]))
 if child[0]=='C':pos=skip_node(pos)
 else:assert child[0]=='K'
assert pos==len(body)
probe=header+'''import PackedData
namespace C16Frames.PackedPrototype
set_option maxRecDepth 100000
set_option maxHeartbeats 0
def rootState : C16Frames.CertGPT.SearchState := {
  need := 128, residual := (Array.range 128).map (fun c => 1 <<< c),
  live := Array.range itemCount }
-- One actual certificate node's coverage predicate; not full acceptance.
theorem root_branch_ok :
    (C16Frames.CertGPT.concreteRules instanceData).branchOk rootState
'''+f'    ({r[1]}, {r[2]}) {children} = true := by decide +kernel\n'+'''
#print axioms root_branch_ok
end C16Frames.PackedPrototype
'''
a.output.with_name('RootProbe.lean').write_text(probe)
print(json.dumps(dict(output=str(a.output),items=ni,tokens=len(tokens),nodes=sum(r.split()[0] in ['R','E','B'] for r in records[1:-1]),sha256=hashlib.sha256(a.output.read_bytes()).hexdigest())))
