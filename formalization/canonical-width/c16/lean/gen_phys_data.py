#!/usr/bin/env python3
"""Write PhysData.lean from physical-pool-source.json (qubit supports, no derived data).
Records the SHA-256 of the source file in the generated header."""
import hashlib, json
from pathlib import Path
here = Path(__file__).resolve().parent
src = (here.parent / 'physical-pool-source.json').read_bytes(); d = json.loads(src)
def lst(xs): return '[' + ', '.join(map(str, xs)) + ']'
out = ['/- Generated by gen_phys_data.py. Do not edit.',
       f'   physical-pool-source.json sha256 {hashlib.sha256(src).hexdigest()}',
       '   canonical_seeds: 8 seeds of the width-18 frame (X and Z supports); each is shifted 16 ways.',
       '   Z_orbit_representatives: 45 Z supports; each is shifted 16 ways (720 Z pool operators). -/',
       'namespace C16Frames.Phys', '']
out.append('def canonSeedX : List (List Nat) := [')
out += ['  ' + lst(r['X']) + (',' if k < len(d['canonical_seeds']) - 1 else '') for k, r in enumerate(d['canonical_seeds'])]
out += [']', '', 'def canonSeedZ : List (List Nat) := [']
out += ['  ' + lst(r['Z']) + (',' if k < len(d['canonical_seeds']) - 1 else '') for k, r in enumerate(d['canonical_seeds'])]
out += [']', '', 'def zReps : List (List Nat) := [']
out += ['  ' + lst(r) + (',' if k < len(d['Z_orbit_representatives']) - 1 else '') for k, r in enumerate(d['Z_orbit_representatives'])]
out += [']', '', 'end C16Frames.Phys']
(here / 'PhysData.lean').write_text('\n'.join(out) + '\n')
print('ok', hashlib.sha256(src).hexdigest()[:16], len(d['canonical_seeds']), len(d['Z_orbit_representatives']))
