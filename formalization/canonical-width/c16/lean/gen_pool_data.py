#!/usr/bin/env python3
"""Write PoolData.lean from pools/xcoords.txt and pools/zcoords.txt (no other input).
Records the SHA-256 of both source files in the generated header."""
import hashlib
from pathlib import Path
here = Path(__file__).resolve().parent; pools = here.parent / 'pools'
src = {s: (pools / f'{s}coords.txt').read_bytes() for s in 'xz'}
vals = {s: [int(v, 16) for v in src[s].decode().split()] for s in 'xz'}
assert all(len(v) == 720 for v in vals.values()) and all(0 <= x < 2**128 for v in vals.values() for x in v)
out = ['/- Generated by gen_pool_data.py. Do not edit.',
       *(f'   pools/{s}coords.txt sha256 {hashlib.sha256(src[s]).hexdigest()}' for s in 'xz'),
       '   Entry 16a+t is T^t applied to orbit representative a; bit c is logical coordinate c. -/',
       'namespace C16Frames.Pools', '']
for s in 'xz':
    out.append(f'def {s}Arr : Array Nat := #[')
    out += [f'  0x{v:032x}' + (',' if k < 719 else '') for k, v in enumerate(vals[s])]
    out += [']', '']
out.append('end C16Frames.Pools')
(here / 'PoolData.lean').write_text('\n'.join(out) + '\n')
print('wrote PoolData.lean', {s: hashlib.sha256(src[s]).hexdigest()[:16] for s in 'xz'})
