#!/usr/bin/env python3
"""Authenticate/decode an unsharded certificate for the Lean executable checker.
No search result is trusted. This Python decoder is not a formal proof bridge.
"""
import argparse, gzip, hashlib, json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def verified(path):
    path = path.resolve()
    manifest = json.loads((ROOT/'restricted-frames-20261031/certificates/MANIFEST.json').read_text())
    data = path.read_bytes()
    key = str(path.relative_to(ROOT))
    assert hashlib.sha256(data).hexdigest() == manifest[key]['sha256'], f'SHA mismatch: {key}'
    return data

def generate(inst, cert, out, pools='real'):
    lines = verified(inst).decode().splitlines()
    nx,nz,ni,dim=map(int,lines[0].split()); assert dim == 128
    vec=lambda s: int(s.split()[0],16) | int(s.split()[1],16)<<64
    assert vec(lines[1]) == 2**128-1
    x=list(map(vec,lines[2:2+nx])); z=list(map(vec,lines[2+nx:2+nx+nz]))
    pooldir=ROOT/'pools' if pools=='real' else ROOT/'independent-check/inputs'
    prefix='' if pools=='real' else 'planted1-'
    assert x==[int(t,16) for t in (pooldir/(prefix+'xcoords.txt')).read_text().split()]
    assert z==[int(t,16) for t in (pooldir/(prefix+'zcoords.txt')).read_text().split()]
    assert len(lines)==2+nx+nz+ni
    items=[]
    for line in lines[2+nx+nz:]:
        a=list(map(int,line.split())); assert len(a)==1+2*a[0]
        assert a[0]>0
        assert all(0<=i<nx and 0<=j<nz for i,j in zip(a[1::2],a[2::2]))
        items.extend(a)
    records=gzip.decompress(verified(cert)).decode().splitlines()
    h=records[0].split()
    assert h[:2]==['C16CERT','1']
    assert len(h)==14
    header=dict(zip(h[2::2],map(int,h[3::2])))
    assert header==dict(need=128,items=ni,live_sides=1,shard=0,nshard=1,shard_depth=0)
    assert records[-1]=='END COMPLETE'
    op={'R':(0,0),'E':(1,2),'B':(2,3),'C':(3,1),'K':(4,1),'S':(5,1),'F':(6,0)}
    tokens=[]
    for line in records[1:-1]:
        t=line.split(); code,n=op[t[0]]; assert len(t)==n+1
        args=list(map(int,t[1:])); assert all(a>=0 for a in args)
        tokens.extend([code,*args])
    data=[nx,nz,ni,*x,*z,*items,len(tokens),*tokens]
    out.write_text(' '.join(map(str,data))+'\n')
    print(json.dumps(dict(output=str(out),items=ni,tokens=len(tokens),sha256=hashlib.sha256(out.read_bytes()).hexdigest())))
if __name__=='__main__':
    p=argparse.ArgumentParser(); p.add_argument('instance',type=Path); p.add_argument('certificate',type=Path);p.add_argument('output',type=Path);p.add_argument('--pools',choices=['real','planted'],default='real');p.add_argument('--lean',type=Path);a=p.parse_args()
    generate(a.instance,a.certificate,a.output,a.pools)

    if a.lean:
        encoded=a.output.read_text().strip()
        sha=hashlib.sha256(a.output.read_bytes()).hexdigest()
        a.lean.write_text('/- Generated by CertGPTGen.py. Decoded stream SHA-256: '+sha+' -/\nimport Std\nnamespace C16Frames.CertGPT\n@[noinline] def swapEncoded : String := '+json.dumps(encoded)+'\nend C16Frames.CertGPT\n')
