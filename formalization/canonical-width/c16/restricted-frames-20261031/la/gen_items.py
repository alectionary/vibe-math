#!/usr/bin/env python3
"""Instances for la_gen.c: frames invariant under an involution / subgroup of the symmetry group.

The frame problem depends only on G = X Z^T (720 x 720, symmetric, T-invariant); its full symmetry
group is T^k x {id, swap} (order 32; explore/gram_wl.py). A frame invariant under a subgroup H is a
union of H-orbits of pairs, so items = H-orbits of pairs that are partial frames.

  gen_items.py [--plant SEED] order L OUT   H = <T^(16/L)>  (validation against la_dfs instances)
  gen_items.py [--plant SEED] swap OUT      H = {id, s},       s(i,j) = (j,i)
  gen_items.py [--plant SEED] swapT8 OUT    H = {id, s T^8},   (i,j) -> (tau j, tau i), tau = T^8 on indices
  gen_items.py verify OUT FRAMES            check every FRAME line: 128 pairs, Gram = identity, distinct
"""
import sys
from pathlib import Path
root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
X = [int(v, 16) for v in (root / 'pools/xcoords.txt').read_text().split()]
Z = [int(v, 16) for v in (root / 'pools/zcoords.txt').read_text().split()]
dot = lambda u, v: bin(u & v).count('1') & 1
def h64(v): return f'{v & (2**64 - 1):x} {v >> 64:x}'

def partial_frame(pairs):
    return len({i for i, _ in pairs}) == len(pairs) and len({j for _, j in pairs}) == len(pairs) and \
        all(dot(X[i], Z[j]) == (a == b) for a, (i, _) in enumerate(pairs) for b, (_, j) in enumerate(pairs))

def orbit_items(gens):
    """items = orbits of valid pairs under the group generated by the given maps on pairs"""
    seen = set(); items = []
    N = len(X)
    for i in range(N):
        for j in range(N):
            if (i, j) in seen or not dot(X[i], Z[j]): continue
            orb = {(i, j)}; frontier = [(i, j)]
            while frontier:
                p = frontier.pop()
                for g in gens:
                    r = g(p)
                    if r not in orb: orb.add(r); frontier.append(r)
            seen |= orb
            orb = sorted(orb)
            if partial_frame(orb): items.append(orb)
    return items

def write(out, items):
    with open(out, 'w') as f:
        f.write(f'{len(X)} {len(Z)} {len(items)} 128\n{h64(2**128 - 1)}\n')
        for v in X: f.write(h64(v) + '\n')
        for v in Z: f.write(h64(v) + '\n')
        for it in items: f.write(f'{len(it)} ' + ' '.join(f'{i} {j}' for i, j in it) + '\n')
    from collections import Counter
    print(out, 'items', len(items), 'by size', dict(Counter(len(it) for it in items)))

def verify(frames_file):
    n = 0
    for line in open(frames_file):
        if not line.startswith('FRAME'): continue
        v = list(map(int, line.split()[1:])); pairs = list(zip(v[0::2], v[1::2]))
        ok = len(pairs) == 128 and partial_frame(pairs) and all(i < 720 and j < 720 for i, j in pairs)
        okp = len(pairs) == 128 and partial_frame(pairs)
        print('VERIFIED frame' if ok else ('VERIFIED frame (uses planted vectors)' if okp else 'FAILED'), len(pairs), 'pairs')
        n += 1
    print('frames checked', n)

if __name__ == '__main__':
    args = sys.argv[1:]
    if args[0] == '--plant':
        from gen_instance import plant
        A, Zd = plant(int(args[1])); X.extend(A); Z.extend(Zd); args = args[2:]
    mode = args[0]
    tau = lambda i: 16 * (i // 16) + (i % 16 + 8) % 16
    if mode == 'verify':
        verify(args[2]); sys.exit()
    if mode == 'order':
        L = int(args[1]); d = 16 // L; out = args[2]
        sh = lambda i: 16 * (i // 16) + (i % 16 + d) % 16
        items = orbit_items([lambda p: (sh(p[0]), sh(p[1]))])
    elif mode == 'swap':
        out = args[1]; items = orbit_items([lambda p: (p[1], p[0])])
    elif mode == 'swapT8':
        out = args[1]; items = orbit_items([lambda p: (tau(p[1]), tau(p[0]))])
    write(out, items)
