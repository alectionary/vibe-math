#!/usr/bin/env python3
"""Exact minimum-weight frames invariant under a cyclic subgroup of order L.

Selected subgroup orbits have size L. A block between selected X/Z orbits
must be zero or a permutation circulant, so its bit pattern is zero or one
monomial. This is a restricted construction search; negative results do not
exclude asymmetric full frames. Positive128-pair witnesses are unrestricted
frames and are sent to the separate physical checker.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import time
from pysat.card import CardEnc,EncType
from frame_sat import SharedCounters
from add_frame_symmetry import lex_clauses


def encode(patterns,target,coverage=False):
    m=len(patterns);counter=SharedCounters(2*m);clauses=counter.clauses
    U=[sum((f.bit_count()==1)<<j for j,f in enumerate(row)) for row in patterns]
    UT=[sum((patterns[i][j].bit_count()==1)<<i for i in range(m)) for j in range(m)]
    for i,row in enumerate(patterns):
        for j,f in enumerate(row):
            if f.bit_count()>1:clauses.append([-i-1,-m-j-1])
    for a,mask in enumerate(U):
        if not mask:clauses.append([-a-1]);continue
        one,two=counter.count(mask,m);clauses.append([-a-1,one])
        if two:clauses.append([-a-1,-two])
    for b,mask in enumerate(UT):
        if not mask:clauses.append([-m-b-1]);continue
        one,two=counter.count(mask,0);clauses.append([-m-b-1,one])
        if two:clauses.append([-m-b-1,-two])
    if coverage:
        for i in range(m):
            clauses.append([m+j+1 for j in range(m) if patterns[i][j]])
            clauses.append([j+1 for j in range(m) if patterns[j][i]])
    top=counter.top
    for offset in [0,m]:
        enc=CardEnc.equals([offset+i+1 for i in range(m)],target,top_id=top,encoding=EncType.kmtotalizer);clauses.extend(enc.clauses);top=enc.nv
    return clauses,top


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--order',type=int,choices=[2,4,8,16],required=True);ap.add_argument('--output',type=Path,required=True);ap.add_argument('--kissat',type=Path,required=True);ap.add_argument('--drat-trim',type=Path,required=True);ap.add_argument('--seconds',type=int,default=120);ap.add_argument('--proof-seconds',type=int,default=120);ap.add_argument('--unsat-search',action='store_true');args=ap.parse_args();root=Path(__file__).parent;L=args.order;d=16//L;X=[int(v,16) for v in (root/'pools/xcoords.txt').read_text().split()];Z=[int(v,16) for v in (root/'pools/zcoords.txt').read_text().split()];m=45*d;target=128//L
    patterns=[[sum(((X[16*a+p]&Z[16*b+q+d*h]).bit_count()%2)<<h for h in range(L)) for b in range(45) for q in range(d)] for a in range(45) for p in range(d)]
    assert all((X[16*(i//d)+i%d+d*s]&Z[16*(j//d)+j%d+d*t]).bit_count()%2==(patterns[i][j]>>((t-s)%L)&1) for i in range(m) for j in range(m) for s in range(L) for t in range(L))
    clauses,top=encode(patterns,target,coverage=True)
    for base in [0,m]:
        enc=CardEnc.atmost([base+12*d+p+1 for p in range(d)],11//L,top_id=top,encoding=EncType.seqcounter);clauses.extend(enc.clauses);top=enc.nv
    for sector in [0,m]:
        for h in range(d):
            if sector==0 and h==0:continue
            right=[sector+(i//d)*d+(i%d-h)%d+1 for i in range(m)];rows,top=lex_clauses(list(range(1,m+1)),right,top);clauses.extend(rows)
    cnf=args.output.with_suffix('.cnf');proof=args.output.with_suffix('.drat');log=args.output.with_suffix('.log')
    with cnf.open('w') as out:
        out.write(f'p cnf {top} {len(clauses)}\n')
        for row in clauses:out.write(' '.join(map(str,row))+' 0\n')
    result={'status':'RUNNING','scope':f'full128-pair weight16 frame invariant under the subgroup generated by T^{d}','subgroup_order':L,'subgroup_orbits_per_sector':m,'selected_orbits_per_sector':target,'variables':top,'clauses':len(clauses),'cnf_sha256':hashlib.sha256(cnf.read_bytes()).hexdigest()};args.output.write_text(json.dumps(result,indent=2)+'\n');start=time.monotonic()
    with log.open('w') as out:
        try:run=subprocess.run([str(args.kissat),*(['--unsat'] if args.unsat_search else []),f'--time={args.seconds}',str(cnf),str(proof)],stdout=out,stderr=subprocess.STDOUT,timeout=args.seconds+10);code=run.returncode
        except subprocess.TimeoutExpired:code=-15
    text=log.read_text();result.update(returncode=code,seconds=time.monotonic()-start)
    if 's SATISFIABLE' in text:
        model={int(s) for line in text.splitlines() if line.startswith('v ') for s in line[2:].split() if int(s)>0};chosenX=[i for i in range(m) if i+1 in model];chosenZ=[j for j in range(m) if m+j+1 in model];assert len(chosenX)==len(chosenZ)==target;pairs=[]
        for i in chosenX:
            partners=[j for j in chosenZ if patterns[i][j]];assert len(partners)==1;j=partners[0];f=patterns[i][j];assert f.bit_count()==1;h=f.bit_length()-1
            for s in range(L):pairs.append([16*(i//d)+i%d+d*s,16*(j//d)+j%d+d*((s+h)%L)])
        assert len(pairs)==128 and all((X[i]&Z[j]).bit_count()%2==(a==b) for a,(i,_) in enumerate(pairs) for b,(_,j) in enumerate(pairs));result.update(status='SAT_POOL_WITNESS',pool_pairs=pairs)
    elif 's UNSATISFIABLE' in text:
        result['status']='UNSAT_PENDING_CERTIFICATE';args.output.write_text(json.dumps(result,indent=2)+'\n');proof_start=time.monotonic()
        try:
            checked=subprocess.run([str(args.drat_trim),str(cnf),str(proof)],capture_output=True,text=True,timeout=args.proof_seconds);args.output.with_suffix('.checked.log').write_text(checked.stdout+checked.stderr)
            if checked.returncode==0 and 's VERIFIED' in checked.stdout:result['status']='UNSAT_CHECKED_SUBGROUP_ONLY'
        except subprocess.TimeoutExpired:result['proof_check_status']='TIME_LIMIT'
        result['proof_check_seconds']=time.monotonic()-proof_start
        result['proof_sha256']=hashlib.sha256(proof.read_bytes()).hexdigest()
    else:result['status']='UNKNOWN_TIME_LIMIT'
    args.output.write_text(json.dumps(result,indent=2)+'\n');print(json.dumps({k:v for k,v in result.items() if k!='pool_pairs'}),flush=True)


if __name__=='__main__':main()
