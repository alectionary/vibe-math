# Independent adversarial validation; fixtures are not scientific fit evidence.
source('simulation/production_guards.R')
nm <- c('p1','p2')
base <- list(estimates=c(A=.5,C=.3),status=0,objective=123,
 hessian=diag(c(4,8)),covariance=diag(c(.5,.25)),
 jacobian=diag(2),expected_covariances=list(expected_MZ=matrix(c(1,.5,.5,1),2),expected_DZ=matrix(c(1,.3,.3,1),2)),
 free_parameters=setNames(c(.7,.55),nm),gradient=c(0,0))
for(k in c('hessian','covariance'))dimnames(base[[k]])<-list(nm,nm)
dimnames(base$jacobian)<-list(names(base$estimates),nm)
checks<-list()
check <- function(name,args,valid) {
 result<-tryCatch(do.call(validate_production_fit,args),error=function(e)list(valid=FALSE,reasons=paste('exception',conditionMessage(e))))
 actual<-isTRUE(result$valid)
 checks[[length(checks)+1]]<<-data.frame(fixture=name,expected_valid=valid,actual_valid=actual,passed=identical(actual,valid),reasons=paste(result$reasons,collapse=';'))
 if(!identical(actual,valid))stop(paste('Guard fixture failed:',name,paste(result$reasons,collapse=';')))
 invisible(result)
}
check('valid_diagonal_reference',base,TRUE)
mutate<-function(name,change,valid=FALSE){a<-base;a<-change(a);check(name,a,valid)}
mutate('nonfinite_estimate',function(a){a$estimates[1]<-NaN;a})
mutate('nonfinite_free_parameter',function(a){a$free_parameters[1]<-Inf;a})
mutate('nonfinite_objective',function(a){a$objective<-Inf;a})
mutate('nonzero_optimizer_status',function(a){a$status<-6;a})
mutate('missing_optimizer_status',function(a){a$status<-NA;a})
mutate('nonfinite_hessian',function(a){a$hessian[1,1]<-Inf;a})
mutate('singular_hessian',function(a){a$hessian[1,1]<-0;a})
mutate('indefinite_hessian',function(a){a$hessian[1,1]<- -4;a})
mutate('asymmetric_hessian',function(a){a$hessian[1,2]<-.1;a})
mutate('nonfinite_parameter_covariance',function(a){a$covariance[1,1]<-NaN;a})
mutate('singular_parameter_covariance',function(a){a$covariance[1,1]<-0;a})
mutate('negative_delta_variance',function(a){a$covariance[1,1]<- -.5;a})
mutate('tiny_negative_delta_not_clipped',function(a){a$covariance[1,1]<- -1e-16;a})
mutate('asymmetric_parameter_covariance',function(a){a$covariance[1,2]<-.1;a})
mutate('wrong_hessian_covariance_scale',function(a){a$covariance<-a$covariance*2;a})
mutate('covariance_label_permutation',function(a){dimnames(a$covariance)<-list(rev(nm),rev(nm));a})
mutate('hessian_label_permutation',function(a){dimnames(a$hessian)<-list(rev(nm),rev(nm));a})
mutate('nonfinite_jacobian',function(a){a$jacobian[1,1]<-Inf;a})
mutate('zero_delta_standard_error',function(a){a$jacobian[1,]<-0;a})
mutate('indefinite_expected_covariance',function(a){a$expected_covariances$expected_MZ<-matrix(c(1,2,2,1),2);a})
mutate('asymmetric_expected_covariance',function(a){a$expected_covariances$expected_MZ[1,2]<-.9;a})
mutate('nonfinite_expected_covariance',function(a){a$expected_covariances$expected_MZ[1,1]<-NA;a})
mutate('near_singular_correlation',function(a){a$expected_covariances$expected_MZ<-matrix(c(1,1-1e-12,1-1e-12,1),2);a})
# Units differ greatly, but well-conditioned correlation matrices remain valid.
mutate('valid_unit_rescaling',function(a){D<-diag(c(1e-4,1e4));a$hessian<-D%*%a$hessian%*%D;a$covariance<-solve(D)%*%a$covariance%*%solve(D);dimnames(a$hessian)<-dimnames(a$covariance)<-list(nm,nm);a},TRUE)
mutate('missing_expected_covariances',function(a){a$expected_covariances<-list();a})
mutate('missing_DZ_covariance',function(a){a$expected_covariances$expected_DZ<-NULL;a})
mutate('jacobian_row_permutation',function(a){rownames(a$jacobian)<-rev(names(a$estimates));a})
mutate('tiny_unit_asymmetric_covariance',function(a){a$expected_covariances$expected_MZ<-matrix(c(1e-12,1e-13,3e-13,1e-12),2);a})
mutate('mixed_unit_asymmetric_covariance',function(a){a$expected_covariances$expected_MZ<-matrix(c(1e-8,1e-3,1e-2,1e8),2);a})
res<-do.call(rbind,checks)
write.csv(res,'outputs/production-guard-fixtures.csv',row.names=FALSE)
cat('Independent guard fixtures passed:',nrow(res),'\n')
