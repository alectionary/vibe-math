# Record the R 4.2.2 session used for the Jeffries replay.
# Usage: Rscript record_session.R OUTFILE
args <- commandArgs(TRUE)
out <- args[1]
dir.create(dirname(out), recursive = TRUE, showWarnings = FALSE)
con <- file(out, "wt")
sink(con, split = TRUE)
cat("recorded_utc: ", format(Sys.time(), tz = "UTC", usetz = TRUE), "\n", sep = "")
cat("uname: ")
cat(system("uname -a", intern = TRUE), "\n", sep = "\n")
cat("nproc: ", system("nproc", intern = TRUE), "\n", sep = "")
cat("R.version.string: ", R.version.string, "\n", sep = "")
cat("R.home: ", R.home(), "\n", sep = "")
cat("La_library: ", La_library(), "\n", sep = "")
cat("La_version: ", La_version(), "\n", sep = "")
cat("extSoftVersion:\n")
print(extSoftVersion())
cat("\n.libPaths:\n")
print(.libPaths())
ip <- installed.packages()
wanted <- c("lavaan", "simsem", "dynamic")
cat("\npackage versions:\n")
print(ip[wanted, c("Package", "Version", "Built")])
suppressMessages({
  library(lavaan)
  library(simsem)
  library(dynamic)
})
cat("\nsessionInfo after library(lavaan); library(simsem); library(dynamic):\n")
print(sessionInfo())
cat("\nRNGkind:\n")
print(RNGkind())
sink()
close(con)
